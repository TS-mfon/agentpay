import { test, expect } from "@playwright/test";
const vault="0x3333333333333333333333333333333333333333";
const detail=`/agent/${vault}`;
const consolePath=`/console?treasuryId=${vault}`;
const history=`/history?treasuryId=${vault}`;

test("distinct agent, payment, history and controls pages preserve governed workflow",async({page,request})=>{
 await page.goto("/agents");
 await expect(page.getByText("Demo · simulated",{exact:true})).toBeVisible();
 await page.getByRole("link",{name:"Open Research scout agent"}).click();
 await expect(page).toHaveURL(new RegExp(`/agent/${vault}`));
 await expect(page.getByRole("heading",{name:"Research scout",exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:"Request a payment.",exact:true})).toHaveCount(0);
 await expect(page.getByRole("heading",{name:"Every request has a record.",exact:true})).toHaveCount(0);
 await page.getByRole("link",{name:"Request a payment",exact:true}).click();
 await expect(page).toHaveURL(new RegExp("/console"));
 await page.getByRole("button",{name:"Research API",exact:true}).click();
 await page.getByRole("button",{name:"Submit payment request",exact:true}).click();
 await expect(page.getByText("Payment request recorded.",{exact:true})).toBeVisible();
 await page.getByRole("link",{name:"View request history",exact:true}).click();
 const research=page.getByRole("row").filter({has:page.getByRole("rowheader").filter({hasText:"Research API"})});
 await expect(research.getByText("Settled",{exact:true})).toBeVisible();
 await research.getByRole("button",{name:"View Research API request"}).click();
 await expect(page.getByRole("dialog")).toContainText("Simulated receipt");
 await expect(page.getByRole("dialog")).toContainText("Demo simulation. No on-chain transaction.");
 await page.getByRole("button",{name:"Close record"}).click();
 await page.goto(consolePath);
 await page.getByRole("button",{name:"Gaming subscription",exact:true}).click();
 await page.getByLabel("Amount in tUSD8",{exact:true}).fill("4");
 await page.getByRole("button",{name:"Submit payment request",exact:true}).click();
 await page.getByRole("link",{name:"View request history",exact:true}).click();
 const gaming=page.getByRole("row").filter({has:page.getByRole("rowheader").filter({hasText:"Gaming subscription"})});
 await expect(gaming.getByText("Rejected",{exact:true})).toBeVisible();
 await gaming.getByRole("button",{name:"View Gaming subscription request"}).click();
 await expect(page.getByRole("dialog")).toContainText("does not serve the research mandate");
 await page.getByRole("button",{name:"Close record"}).click();
 await page.goto(detail);
 await page.getByRole("button",{name:"Pause treasury",exact:true}).click();
 await expect(page.getByRole("button",{name:"Resume treasury",exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Withdraw unused funds",exact:true}).click();
 await page.getByLabel("Amount in tUSD8",{exact:true}).fill("10");
 await page.getByRole("button",{name:"Withdraw funds",exact:true}).click();
 await expect(page.getByRole("status")).toContainText("Unused funds withdrawn.");
 await page.getByRole("button",{name:"Resume treasury",exact:true}).click();
 await expect(page.getByRole("button",{name:"Pause treasury",exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Agent API key",exact:true}).click();
 await page.getByRole("button",{name:"Rotate and reveal new key"}).click();
 const key=await page.getByLabel("Copy this key now").inputValue();
 expect(key).toMatch(/^ap_/);
 expect((await request.get("/api/v1/payments",{headers:{authorization:`Bearer ${key}`}})).status()).toBe(200);
 for (const path of ["/api/v1/treasury", "/api/v1/policy"])
   expect((await request.get(path, { headers: { authorization: `Bearer ${key}` } })).status()).toBe(404);
 await page.keyboard.press("Escape");
 await page.getByRole("button",{name:"Revoke agent",exact:true}).click();
 await page.getByRole("dialog").getByRole("button",{name:"Revoke agent",exact:true}).click();
 expect((await request.get("/api/v1/payments",{headers:{authorization:`Bearer ${key}`}})).status()).toBe(401);
 await expect(page.getByRole("button",{name:"Authorize agent again"})).toBeVisible();
 await page.getByRole("button",{name:"Authorize agent again"}).click();
 await expect(page.getByRole("button",{name:"Revoke agent",exact:true})).toBeVisible();
 await page.screenshot({path:".local/qa/agent-detail.png",fullPage:true});
 await page.goto(history);
 await expect(page.getByRole("heading",{name:"Request history.",exact:true})).toBeVisible();
});

test("mobile agent detail and keyboard controls remain usable",async({page})=>{
 await page.setViewportSize({width:360,height:800});
 await page.goto(detail);
 await expect(page.getByRole("button",{name:"Withdraw unused funds",exact:true})).toBeVisible({timeout:20000});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole("button",{name:"Withdraw unused funds",exact:true}).click();
 await expect(page.getByRole("dialog")).toBeVisible();
 await page.keyboard.press("Escape");
 await expect(page.getByRole("dialog")).not.toBeVisible();
 await page.screenshot({path:".local/qa/agent-detail-mobile.png",fullPage:true});
});
