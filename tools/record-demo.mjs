import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdir,copyFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
const origin='http://localhost:3000';
const server=spawn(process.execPath,['node_modules/next/dist/bin/next','dev','--hostname','127.0.0.1','--port','3000'],{env:{...process.env,AGENTPAY_MODE:'demo',APP_ORIGIN:origin,MONGODB_URI:'',AGENTPAY_DEMO_STATE:`.local/video-${randomUUID()}.json`},stdio:['ignore','ignore','inherit']});
let browser;
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
try {
  await mkdir('.local/video',{recursive:true});
  let ready=false;
  for(let attempt=0;attempt<90;attempt++){try{ready=(await fetch(origin+'/api/owner/dashboard')).ok;}catch{}if(ready)break;await wait(1000);}
  if(!ready)throw new Error('Demo server did not start');
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:'.local/video',size:{width:1280,height:800}}});
  const page=await context.newPage();
  await page.goto(origin);
  await page.getByRole('button',{name:'Withdraw unused funds',exact:true}).waitFor({timeout:30000});
  const caption=async text=>{await page.evaluate(value=>{let label=document.getElementById('demo-caption');if(!label){label=document.createElement('div');label.id='demo-caption';label.style.cssText='position:fixed;bottom:16px;left:50%;transform:translateX(-50%);z-index:9999;background:#142e50;color:white;padding:14px 22px;border-radius:12px;max-width:80vw;font:600 16px system-ui;text-align:center;box-shadow:0 8px 30px #142e5050;pointer-events:none';document.body.append(label);}label.textContent=value;},text);await wait(2500);};
  await caption('AgentPay prototype: simulated walkthrough. Live mode uses GenLayer and Aevum.');
  await caption('The owner gives a research agent a mandate and a 40 tUSD8 weekly budget.');
  const service=page.getByRole('article').filter({has:page.getByRole('heading',{name:'Research API',exact:true})});
  await service.getByRole('button',{name:'Request payment'}).click();
  await caption('The agent requests 4 tUSD8 for a research API.');
  await page.getByRole('button',{name:'Submit payment request'}).click();
  const research=page.getByRole('row').filter({has:page.getByRole('rowheader').filter({hasText:'Research API'})});
  await research.getByText('Settled',{exact:true}).waitFor({timeout:30000});
  await research.getByRole('button',{name:'View Research API request'}).click();
  await caption('The record joins the request, mandate version, explanation and receipt. This receipt is simulated.');
  await page.getByRole('button',{name:'Close record'}).click();
  await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Gaming subscription',exact:true})}).getByRole('button',{name:'Request payment'}).click();
  await page.getByLabel('Amount in tUSD8',{exact:true}).fill('4');
  await caption('The same 4 tUSD8 amount can still violate the agent’s purpose.');
  await page.getByRole('button',{name:'Submit payment request'}).click();
  const gaming=page.getByRole('row').filter({has:page.getByRole('rowheader').filter({hasText:'Gaming subscription'})});
  await gaming.getByText('Rejected',{exact:true}).waitFor({timeout:30000});
  await gaming.getByRole('button',{name:'View Gaming subscription request'}).click();
  await caption('An unrelated entertainment request is rejected. No payment executes.');
  await page.getByRole('button',{name:'Close record'}).click();
  await page.getByRole('button',{name:'Pause treasury',exact:true}).click();
  await page.getByRole('button',{name:'Resume treasury',exact:true}).waitFor();
  await page.getByRole('button',{name:'Withdraw unused funds',exact:true}).click();
  await page.getByLabel('Amount in tUSD8',{exact:true}).fill('10');
  await caption('The owner can stop spending and withdraw unused funds, even while paused.');
  await page.getByRole('button',{name:'Withdraw funds',exact:true}).click();
  await page.getByRole('button',{name:'Resume treasury',exact:true}).click();
  await page.getByRole('button',{name:'Pause treasury',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Every request has a record.'}).scrollIntoViewIfNeeded();
  await caption('Intelligent mandates. Enforced budgets. Inspectable payments.');
  await page.screenshot({path:'.local/qa/desktop-final.png',fullPage:true});
  await context.close();
  const video=await page.video().path();
  await copyFile(video,'public/demo.webm');
  console.log('Recorded prototype walkthrough: public/demo.webm (simulated, no live deployment claim).');
} finally {if(browser)await browser.close();server.kill('SIGINT');}
